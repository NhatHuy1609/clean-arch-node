import { DomainError } from '../shared/DomainError';
import { ProductCode } from './ProductCode';

const NAME_MAX_LENGTH = 200;
const DESCRIPTION_MAX_LENGTH = 2000;

/** Raw Product data — used to persist and restore. Contains no behaviour. */
export interface ProductSnapshot {
  id: string;
  code: string;
  name: string;
  description: string;
  createdAt: Date;
  updatedAt: Date | null;
}

export interface CreateProductProps {
  id: string;
  code: string;
  name: string;
  description?: string;
  now: Date;
}

/**
 * Aggregate root `Product`.
 *
 * Compared with `Product.cs` in Practical.CleanArchitecture (all `get; set;`):
 * - No public setters: state only changes through methods with business meaning (`rename`, ...).
 * - Invariants are checked inside the entity → an invalid Product cannot exist.
 * - Time is passed in (from the application's `Clock` port) instead of calling `new Date()`
 *   → a pure domain and deterministic tests.
 * - `id` is supplied from outside (`IdGenerator` port), not generated by the database.
 */
export class Product {
  private constructor(
    readonly id: string,
    readonly code: ProductCode,
    private _name: string,
    private _description: string,
    private readonly _createdAt: Date,
    private _updatedAt: Date | null,
  ) {}

  static create(props: CreateProductProps): Product {
    return new Product(
      props.id,
      ProductCode.create(props.code),
      validateName(props.name),
      validateDescription(props.description ?? ''),
      new Date(props.now),
      null,
    );
  }

  /** Rebuilds a Product from stored data (used by repositories). */
  static restore(snapshot: ProductSnapshot): Product {
    return new Product(
      snapshot.id,
      ProductCode.create(snapshot.code),
      snapshot.name,
      snapshot.description,
      new Date(snapshot.createdAt),
      snapshot.updatedAt ? new Date(snapshot.updatedAt) : null,
    );
  }

  get name(): string {
    return this._name;
  }

  get description(): string {
    return this._description;
  }

  get createdAt(): Date {
    return new Date(this._createdAt);
  }

  get updatedAt(): Date | null {
    return this._updatedAt ? new Date(this._updatedAt) : null;
  }

  rename(name: string, now: Date): void {
    const next = validateName(name);
    if (next === this._name) return;
    this._name = next;
    this._updatedAt = new Date(now);
  }

  changeDescription(description: string, now: Date): void {
    const next = validateDescription(description);
    if (next === this._description) return;
    this._description = next;
    this._updatedAt = new Date(now);
  }

  toSnapshot(): ProductSnapshot {
    return {
      id: this.id,
      code: this.code.value,
      name: this._name,
      description: this._description,
      createdAt: this.createdAt,
      updatedAt: this.updatedAt,
    };
  }
}

function validateName(raw: string): string {
  const name = raw.trim();
  if (name.length === 0 || name.length > NAME_MAX_LENGTH) {
    throw new DomainError('product.invalid_name', `Product name must be 1-${NAME_MAX_LENGTH} characters.`);
  }
  return name;
}

function validateDescription(raw: string): string {
  const description = raw.trim();
  if (description.length > DESCRIPTION_MAX_LENGTH) {
    throw new DomainError(
      'product.invalid_description',
      `Product description must be at most ${DESCRIPTION_MAX_LENGTH} characters.`,
    );
  }
  return description;
}
